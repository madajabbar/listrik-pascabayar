--  * Di lingkungan produksi, hak app_listrik sebaiknya dipersempit lagi
--    menjadi hanya SELECT/INSERT/UPDATE/DELETE + EXECUTE pada routine,
--    sedangkan DDL (CREATE/ALTER/DROP) dijalankan akun migrasi terpisah.
